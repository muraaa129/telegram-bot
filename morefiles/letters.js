let lastIndex = -1; // checker for the last letter
export function getRandomLetter(arr) {
    let randomIndex;
    
    do {
        randomIndex = Math.floor(Math.random() * arr.length); // generate new index
    } while (randomIndex === lastIndex);
    // note: loop continues while statement in () is true
    // loop continues when randomIndex equals lastIndex

    lastIndex = randomIndex; // update memory with current index

    return arr[randomIndex];
}